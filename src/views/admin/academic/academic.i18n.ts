export function useAcademicI18n() {
  const { locale } = useI18n();
  const isBn = locale === 'bn';

  const t = <T extends { bn: string; en: string }>(item: T): string => {
    return isBn ? item.bn : item.en;
  };

  return { locale, isBn, t, dict: ACADEMIC_DICTIONARY };
}
